    # CALL LLM
    # ========================================================

    try:

        with measure_latency(
            latencies,
            "critic",
            attempt=attempt,
            retry_latencies=retry_latencies
        ):

            response = client.complete(
                CRITIC_PROMPT,
                [
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ],
                max_tokens=256,
                think=False
            )

        response_text = response.content

        print()
        print("RAW CRITIC RESPONSE:")
        print(response_text)

    except Exception as e:

        return {
            "sql_valid": False,
            "critique": (
                f"Critic LLM failed: {str(e)}"
            ),
            "error_type": ErrorType.CRITIC_ERROR.value,
            "latencies": latencies,
            "retry_latencies": retry_latencies,
        }

    # ========================================================
    # PARSE
    # ========================================================

    parsed_result = parse_llm_response(
        response_text
    )

    if not parsed_result.get(
        "parsed",
        False
    ):

        return {
            "sql_valid": False,
            "critique": parsed_result.get(
                "error",
                "Critic returned invalid JSON."
            ),
            "error_type": ErrorType.CRITIC_ERROR.value,
            "latencies": latencies,
            "retry_latencies": retry_latencies,
        }

    parsed = parsed_result.get(
        "data"
    )

    if not isinstance(
        parsed,
        dict
    ):

        return {
            "sql_valid": False,
            "critique": (
                "Critic returned an invalid response format."
            ),
            "error_type": ErrorType.CRITIC_ERROR.value,
            "latencies": latencies,
            "retry_latencies": retry_latencies,
        }

    if "valid" not in parsed:

        return {
            "sql_valid": False,
            "critique": (
                "Critic response is missing the "
                "'valid' field."
            ),
            "error_type": ErrorType.CRITIC_ERROR.value,
            "latencies": latencies,
            "retry_latencies": retry_latencies,
        }

    if not isinstance(
        parsed["valid"],
        bool
    ):

        return {
            "sql_valid": False,
            "critique": (
                "Critic 'valid' field must be a boolean."
            ),
            "error_type": ErrorType.CRITIC_ERROR.value,
            "latencies": latencies,
            "retry_latencies": retry_latencies,
        }

    valid = parsed["valid"]

    feedback = parsed.get(
        "feedback",
        ""
    )

    if feedback is None:
        feedback = ""

    feedback = str(
        feedback
    ).strip()

    return {
        "sql_valid": valid,
        "critique": feedback,
        "error_type": ErrorType.NONE.value,
        "latencies": latencies,
        "retry_latencies": retry_latencies,
    }