# ============================================================
# JSON PARSER
# ============================================================

def parse_llm_response(response_text: str) -> dict:

    if not response_text:

        return {
            "parsed": False,
            "error": "Critic returned an empty response."
        }

    text = response_text.strip()

    if text.startswith("```"):

        lines = text.splitlines()

        if lines:
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        text = "\n".join(
            lines
        ).strip()

    try:

        parsed = json.loads(
            text
        )

        return {
            "parsed": True,
            "data": parsed
        }

    except json.JSONDecodeError:

        return {
            "parsed": False,
            "error": (
                "Critic returned invalid JSON. "
                f"Raw response: {text}"
            )
        }


# ============================================================
# MONTH QUESTION PARSER
# ============================================================

def parse_month_question(question: str):

    normalized = " ".join(
        question.lower().strip().split()
    )

    pattern = re.compile(
        r"how many events "
        r"(?:occurred|were recorded|happened|took place) "
        r"in "
        r"(january|february|march|april|may|june|july|"
        r"august|september|october|november|december) "
        r"(\d{4})"
        r"\??$"
    )

    match = pattern.match(
        normalized
    )

    if not match:
        return None

    return (
        match.group(1),
        int(match.group(2)),
    )


# ============================================================
# AGE QUESTION PARSER
# ============================================================

def parse_older_than_question(question: str):

    normalized = " ".join(
        question.lower().strip().split()
    )

    patterns = [
        r"how many events were generated by users older than (\d+)\??$",
        r"how many events were generated by users over (\d+)\??$",
        r"how many events were produced by users older than (\d+)\??$",
        r"how many events came from users older than (\d+)\??$",
    ]

    for pattern in patterns:

        match = re.match(
            pattern,
            normalized
        )

        if match:
            return int(
                match.group(1)
            )

    return None


